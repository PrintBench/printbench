import { describe, expect, it } from 'vitest'
import { parseGcodeMetadata, parseDuration } from './gcode-metadata'

/*
 * Fixtures are inline strings rather than committed .gcode files. A real sliced
 * file is tens of megabytes of movement commands wrapped around the few hundred
 * bytes of comments this parser cares about, and committing one to test a string
 * parser would be all cost and no signal. These are the comment blocks, copied
 * in the shape each slicer actually writes them.
 */

const PRUSA_TAIL = `
; filament used [mm] = 4123.45
; filament used [cm3] = 9.91
; filament used [g] = 12.34
; total filament used [g] = 12.34
; total filament cost = 0.31
; estimated printing time (normal mode) = 1h 23m 4s
;
; prusaslicer_config = begin
; layer_height = 0.2
; nozzle_diameter = 0.4
; filament_type = PLA
; filament_vendor = Prusa Polymers
; filament_colour = #FF8000
; filament_cost = 24.99
; fill_density = 15%
; perimeters = 3
; support_material = 0
; brim_width = 0
; raft_layers = 0
; skirts = 1
; temperature = 215
; bed_temperature = 60
; printer_model = MK4S
; print_settings_id = 0.20mm SPEED @MK4S
; prusaslicer_config = end
`

const PRUSA_HEAD = `; generated by PrusaSlicer 2.8.0+win64 on 2024-01-01 at 12:00:00 UTC
;
M73 P0 R83
G21 ; set units to millimeters
`

const CURA_HEAD = `;FLAVOR:Marlin
;TIME:3723
;Filament used: 4.12345m
;Layer height: 0.2
;MINX:85.5
;MAXZ:20.4
;TARGET_MACHINE.NAME:Ultimaker S5
;Generated with Cura_SteamEngine 5.7.0
;SETTING_3 {"global_quality": "[general]\\nversion = 4\\n=====", "extr
;SETTING_3 uder_quality": ["[general]\\nversion = 4\\n===================
M104 S200
`

const ORCA_TAIL = `
; total filament weight [g] : 41.20
; model printing time: 2h 5m 30s
; CONFIG_BLOCK_START
; layer_height = 0.16
; nozzle_diameter = 0.6,0.6
; nozzle_type = hardened_steel
; filament_type = "PETG";"PLA"
; filament_vendor = "Bambu"
; sparse_infill_density = 25%
; wall_loops = 4
; enable_support = 1
; brim_type = outer_only
; nozzle_temperature = 255
; hot_plate_temp = 70
; printer_model = Bambu Lab X1 Carbon
; print_settings_id = 0.16mm Optimal @BBL X1C
; CONFIG_BLOCK_END
`

describe('parseGcodeMetadata', () => {
  it('reads a PrusaSlicer config block', () => {
    const result = parseGcodeMetadata(PRUSA_HEAD, PRUSA_TAIL)

    expect(result).toMatchObject({
      nozzleMm: 0.4,
      layerHeightMm: 0.2,
      material: 'PLA',
      filamentBrand: 'Prusa Polymers',
      colorHex: '#ff8000',
      infillPercent: 15,
      wallCount: 3,
      supports: false,
      adhesion: 'skirt',
      nozzleTempC: 215,
      bedTempC: 60,
      durationMin: 83,
      filamentUsedG: 12.34,
      filamentCost: 0.31,
      printerName: 'MK4S',
      slicerName: 'PrusaSlicer',
      slicerVersion: '2.8.0',
      slicerProfile: '0.20mm SPEED @MK4S',
    })
    expect(result.multiMaterial).toBeUndefined()
  })

  it('takes cost per print, not the per-kilogram spool price', () => {
    // filament_cost = 24.99 is the spool; 0.31 is what this print used.
    expect(parseGcodeMetadata('', PRUSA_TAIL).filamentCost).toBe(0.31)
  })

  it('reads a Cura header', () => {
    const result = parseGcodeMetadata(CURA_HEAD, '')

    expect(result).toMatchObject({
      layerHeightMm: 0.2,
      durationMin: 62,
      printerName: 'Ultimaker S5',
      slicerName: 'Cura',
      slicerVersion: '5.7.0',
    })
    // Cura reports filament as a length; converting would mean assuming a
    // diameter and a density, so the field stays empty rather than invented.
    expect(result.filamentUsedG).toBeUndefined()
  })

  it('does not parse keys out of Cura settings blobs', () => {
    // The ;SETTING_3 lines contain "version = 4" and "=====".
    const result = parseGcodeMetadata(CURA_HEAD, '')
    expect(result.slicerProfile).toBeUndefined()
    expect(Object.values(result)).not.toContain('4')
  })

  it('reads an Orca/Bambu config block, including nozzle type', () => {
    const result = parseGcodeMetadata('', ORCA_TAIL)

    expect(result).toMatchObject({
      nozzleMm: 0.6,
      nozzleType: 'hardened_steel',
      layerHeightMm: 0.16,
      material: 'PETG',
      filamentBrand: 'Bambu',
      infillPercent: 25,
      wallCount: 4,
      supports: true,
      adhesion: 'brim',
      nozzleTempC: 255,
      bedTempC: 70,
      durationMin: 126,
      filamentUsedG: 41.2,
      printerName: 'Bambu Lab X1 Carbon',
      slicerProfile: '0.16mm Optimal @BBL X1C',
    })
  })

  it('flags a multi-material file and takes the first value', () => {
    const result = parseGcodeMetadata('', ORCA_TAIL)
    expect(result.multiMaterial).toBe(true)
    expect(result.material).toBe('PETG')
    expect(result.nozzleMm).toBe(0.6)
  })

  it('prefers the trailing config block over the header', () => {
    const head = '; layer_height = 0.3\n'
    const tail = '; layer_height = 0.12\n'
    expect(parseGcodeMetadata(head, tail).layerHeightMm).toBe(0.12)
  })

  it('returns nothing for binary G-code rather than parsing noise', () => {
    expect(parseGcodeMetadata('GCDE\x00\x01nozzle_diameter = 9', '')).toEqual({})
  })

  it('returns nothing for a file with no recognisable comments', () => {
    expect(parseGcodeMetadata('G1 X10 Y10 E1\nG1 X20\n', 'G1 X30\n')).toEqual({})
  })

  it('survives a truncated file', () => {
    expect(() => parseGcodeMetadata('; layer_height =', '; nozzle_dia')).not.toThrow()
    expect(parseGcodeMetadata('; layer_height =', '; nozzle_dia')).toEqual({})
  })

  it('drops values that are out of range rather than storing nonsense', () => {
    const result = parseGcodeMetadata(
      '',
      '; nozzle_diameter = 40\n; layer_height = 900\n; temperature = 9000\n',
    )
    expect(result.nozzleMm).toBeUndefined()
    expect(result.layerHeightMm).toBeUndefined()
    expect(result.nozzleTempC).toBeUndefined()
  })

  it('drops slicer placeholder values', () => {
    const result = parseGcodeMetadata(
      '',
      '; filament_vendor = Undefine\n; printer_model = unknown\n; nozzle_type = undefine\n',
    )
    expect(result.filamentBrand).toBeUndefined()
    expect(result.printerName).toBeUndefined()
    expect(result.nozzleType).toBeUndefined()
  })

  it('maps an unrecognised nozzle material to "other" rather than dropping it', () => {
    expect(parseGcodeMetadata('', '; nozzle_type = stainless_steel\n').nozzleType).toBe('other')
  })

  it('only reports adhesion when the file discussed it', () => {
    expect(parseGcodeMetadata('', '; layer_height = 0.2\n').adhesion).toBeUndefined()
    expect(parseGcodeMetadata('', '; brim_width = 0\n; skirts = 0\n').adhesion).toBe('none')
    expect(parseGcodeMetadata('', '; raft_layers = 4\n; brim_width = 5\n').adhesion).toBe('raft')
  })

  it('distinguishes "no supports" from "unknown"', () => {
    expect(parseGcodeMetadata('', '; support_material = 0\n').supports).toBe(false)
    expect(parseGcodeMetadata('', '; layer_height = 0.2\n').supports).toBeUndefined()
  })

  it('ignores embedded thumbnail base64', () => {
    const tail = [
      '; thumbnail begin 16x16 380',
      '; iVBORw0KGgoAAAANSUhEUgAAABAAAAAQCAYAAAAf8/9hAAAA=',
      '; thumbnail end',
      '; layer_height = 0.2',
    ].join('\n')
    expect(parseGcodeMetadata('', tail)).toEqual({ layerHeightMm: 0.2 })
  })
})

describe('parseDuration', () => {
  it.each([
    ['1h 23m 4s', 83],
    ['2h 5m 30s', 126],
    ['45m', 45],
    ['1d 2h 30m', 1590],
    ['30s', 1],
    ['3h', 180],
  ])('reads %s as %i minutes', (text, expected) => {
    expect(parseDuration(text)).toBe(expected)
  })

  it('returns null for text with no duration in it', () => {
    expect(parseDuration('unknown')).toBeNull()
    expect(parseDuration('')).toBeNull()
  })
})
